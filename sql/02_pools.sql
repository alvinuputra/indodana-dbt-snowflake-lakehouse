-- =====================================================================
-- 02_pools.sql : weighted pick pools for the generator
-- =====================================================================
-- Weighted random choice is done by expanding each reference row into
-- `WEIGHT` numbered slots, picking an integer slot with UNIFORM(), then
-- equi-joining on it. Keeps the generator set-based with no loops.
-- =====================================================================
USE SCHEMA DEMO_INDODANA.GEN;

CREATE OR REPLACE TABLE POOL_CITY AS
SELECT ROW_NUMBER() OVER (ORDER BY c.CITY, n.I) AS IDX, c.CITY, c.PROVINCE
FROM REF_CITY c JOIN NUMBERS n ON n.I <= c.WEIGHT;

CREATE OR REPLACE TABLE POOL_OCCUPATION AS
SELECT ROW_NUMBER() OVER (ORDER BY OCCUPATION) AS IDX, OCCUPATION, INCOME_MULT
FROM REF_OCCUPATION;

CREATE OR REPLACE TABLE POOL_FIRST AS
SELECT ROW_NUMBER() OVER (ORDER BY NAME) AS IDX, NAME, GENDER FROM REF_NAME_FIRST;

CREATE OR REPLACE TABLE POOL_LAST AS
SELECT ROW_NUMBER() OVER (ORDER BY NAME) AS IDX, NAME FROM REF_NAME_LAST;

CREATE OR REPLACE TABLE POOL_DECLINE AS
SELECT ROW_NUMBER() OVER (ORDER BY r.REASON, n.I) AS IDX, r.REASON
FROM REF_DECLINE_REASON r JOIN NUMBERS n ON n.I <= r.WEIGHT;

-- Lead source mix, weighted by Cermati-style acquisition reality
CREATE OR REPLACE TABLE POOL_LEAD_SOURCE AS
SELECT ROW_NUMBER() OVER (ORDER BY s.SRC, n.I) AS IDX, s.SRC AS LEAD_SOURCE, s.CPL
FROM (
  SELECT 'ORGANIC_SEO' AS SRC,  32 AS W,  12000 AS CPL
  UNION ALL SELECT 'PAID_SEARCH', 22,  85000
  UNION ALL SELECT 'SOCIAL',      16,  62000
  UNION ALL SELECT 'AFFILIATE',   14,  48000
  UNION ALL SELECT 'EMAIL_CRM',    9,   9000
  UNION ALL SELECT 'DIRECT',       7,      0
) s JOIN NUMBERS n ON n.I <= s.W;

-- Product mix: paylater dominates by volume, KTA by value
CREATE OR REPLACE TABLE POOL_PRODUCT AS
SELECT ROW_NUMBER() OVER (ORDER BY p.PRODUCT_TYPE, n.I) AS IDX,
       p.PRODUCT_TYPE, p.MIN_AMT, p.MAX_AMT, p.RATE_PA
FROM (
  SELECT 'PAYLATER' AS PRODUCT_TYPE, 45 AS W,   500000 AS MIN_AMT,  15000000 AS MAX_AMT, 0.3120 AS RATE_PA
  UNION ALL SELECT 'KTA',          35,  3000000, 100000000, 0.2280
  UNION ALL SELECT 'MULTIGUNA',    12,  5000000, 150000000, 0.1920
  UNION ALL SELECT 'CREDIT_CARD',   8,  2000000,  40000000, 0.2640
) p JOIN NUMBERS n ON n.I <= p.W;

CREATE OR REPLACE TABLE POOL_CHANNEL AS
SELECT ROW_NUMBER() OVER (ORDER BY c.CH, n.I) AS IDX, c.CH AS PAYMENT_CHANNEL
FROM (
  SELECT 'VA_BCA' AS CH, 24 AS W
  UNION ALL SELECT 'VA_MANDIRI', 18
  UNION ALL SELECT 'AUTODEBIT',  16
  UNION ALL SELECT 'GOPAY',      12
  UNION ALL SELECT 'OVO',        10
  UNION ALL SELECT 'VA_BNI',      8
  UNION ALL SELECT 'ALFAMART',    7
  UNION ALL SELECT 'INDOMARET',   5
) c JOIN NUMBERS n ON n.I <= c.W;

SELECT 'POOL_CITY' AS POOL, COUNT(*) AS SLOTS FROM POOL_CITY
UNION ALL SELECT 'POOL_LEAD_SOURCE', COUNT(*) FROM POOL_LEAD_SOURCE
UNION ALL SELECT 'POOL_PRODUCT', COUNT(*) FROM POOL_PRODUCT
UNION ALL SELECT 'POOL_CHANNEL', COUNT(*) FROM POOL_CHANNEL
UNION ALL SELECT 'POOL_DECLINE', COUNT(*) FROM POOL_DECLINE;
